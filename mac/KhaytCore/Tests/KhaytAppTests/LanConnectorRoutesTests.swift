    @Test("self: a connector is answered and signed back; a phone, the PIN or nothing at all are not")
    func whoMayAsk() async throws {
        let (bench, root) = try await Self.bench()
        defer { bench.stop(); try? FileManager.default.removeItem(at: root) }
        let peer = try Self.enrol(bench)
        let headers = peer.headers("GET", "/api/connectors/self")
        let me = try await bench.send("GET", "/api/connectors/self", headers: headers)
        #expect(me.status == 200, "\(me.text)")
        #expect(me.json["connectorId"] as? String == peer.id)
        #expect(me.json["name"] as? String == "OrcaSlicer on the PC")
        #expect((me.json["shop"] as? [String: Any])?["name"] as? String != nil)
        #expect((me.json["scopes"] as? [String]) == ["slices:send", "queue:read"])
        let nonce = try #require(headers["x-khayt-nonce"])
        #expect(Self.signedBy(me, peer, nonce: nonce), "the answer is signed with the pairing key")
        let forged = LanServerTests.Bench.Reply(status: me.status, headers: me.headers,
                                                body: Data(me.text.replacingOccurrences(of: "OrcaSlicer", with: "Evil").utf8))
        #expect(!Self.signedBy(forged, peer, nonce: nonce), "a changed answer does not verify")

        let phone = try Self.enrol(bench, kind: nil, name: "Bench phone")
        let asPhone = try await Self.call(bench, phone, "GET", "/api/connectors/self")
        #expect(asPhone.status == 403 && asPhone.text.contains("connector-only"))
        let unsigned = try await bench.send("GET", "/api/connectors/self")
        #expect(unsigned.status == 401)
        let withPin = try await bench.send("GET", "/api/connectors/self", headers: ["x-khayt-pin": Self.pin])
        #expect(withPin.status == 403 && withPin.text.contains("connector-only"))
        let stranger = Peer(id: "dev_NotEnrolledAtAll12", key: Data(repeating: 1, count: 32))
        #expect(try await Self.call(bench, stranger, "GET", "/api/connectors/self").status == 401)
        // A signature replayed is refused (the nonce was spent).
        let again = try await bench.send("GET", "/api/connectors/self", headers: headers)
        #expect(again.status == 401 && again.text.contains("device-replay"))
    }

