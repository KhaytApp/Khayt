    @Test("every head refusal is answered from the head, with a GiB declared and not one byte read")
    func headRefusals() async throws {
        let (bench, root) = try await Self.bench()
        defer { bench.stop(); try? FileManager.default.removeItem(at: root) }
        let peer = try Self.enrol(bench)
        let phone = try Self.enrol(bench, kind: nil, name: "Bench phone")
        let port = bench.port
        let (_, sliceId) = try await Self.announce(bench, peer, Self.gcode)
        let path = "\(Self.slices)/\(sliceId)/file"
        let declared = Self.hexSha(Self.gcode)
        func signed(_ p: Peer, _ path: String, _ hash: String) -> [String: String] {
            var h = p.headers("PUT", path, bodyHash: hash)
            h[LanServer.connectorHashHeader] = hash
            return h
        }
        let cases: [(String, [String: String], String, String)] = [
            ("unsigned", [LanServer.connectorHashHeader: declared], "401", "device-auth"),
            ("no hash", peer.headers("PUT", path, bodyHash: declared), "400", "no-hash"),
            ("a phone", signed(phone, path, declared), "403", "connector-only"),
            ("bad signature", { var h = signed(peer, path, declared); h["x-khayt-mac"] = Data(repeating: 0, count: 32).base64EncodedString(); return h }(), "401", "device-auth"),
            ("unknown slice", signed(peer, "\(Self.slices)/QRSTUVWXYZ234567/file", declared), "404", "unknown-slice"),
            ("another hash", signed(peer, path, String(repeating: "a", count: 64)), "409", "hash-not-declared"),
            ("not its length", signed(peer, path, declared), "400", "length-mismatch"),
        ]
        for (name, headers, status, reason) in cases {
            let target = name == "unknown slice" ? "\(Self.slices)/QRSTUVWXYZ234567/file" : path
            let head = Self.gibHead(target, headers: headers)
            let answer = await offPool { Self.raw(port: port, head) }
            #expect(answer.hasPrefix("HTTP/1.1 \(status)"), Comment(rawValue: "\(name): \(answer.prefix(120))"))
            #expect(answer.contains(reason), Comment(rawValue: "\(name): \(answer)"))
            #expect(!answer.contains("100 Continue"), "\(name): the body was never asked for")
        }
        // Slots shared with the OctoPrint path: both taken → busy.
        bench.server.slicerUploads = LanServer.maxSlicerUploads
        let busyHead = Self.gibHead(path, headers: signed(peer, path, declared)).replacingOccurrences(
            of: "Content-Length: \(1 << 30)", with: "Content-Length: \(Self.gcode.count)")
        let busy = await offPool { Self.raw(port: port, busyHead) }
        #expect(busy.hasPrefix("HTTP/1.1 503") && busy.contains("busy"), Comment(rawValue: busy))
        bench.server.slicerUploads = 0
        // The nonce is spent at the head: the same signed head twice is a replay.
        let once = signed(peer, path, declared)
        let onceHead = Self.gibHead(path, headers: once)
        _ = await offPool { Self.raw(port: port, onceHead) }
        let twice = await offPool { Self.raw(port: port, onceHead) }
        #expect(twice.hasPrefix("HTTP/1.1 401") && twice.contains("device-replay"), Comment(rawValue: twice))

        #expect(SlicerInbox.list(root: root).isEmpty)
        #expect(bench.server.slicerUploads == 0, "no slot was kept")
        // Still waiting: none of that cost the slice its chance.
        #expect(try await Self.put(bench, peer, sliceId, Self.gcode).status == 201)
        let againHead = Self.gibHead(path, headers: signed(peer, path, declared))
        let filedAgain = await offPool { Self.raw(port: port, againHead) }
        #expect(filedAgain.hasPrefix("HTTP/1.1 409") && filedAgain.contains("not-awaiting-file"))
    }

    @Test("no oracle on slice ids: an unsigned or forged head is answered the same for a real id and a made-up one")
    func noSliceOracle() async throws {
        let (bench, root) = try await Self.bench()
        defer { bench.stop(); try? FileManager.default.removeItem(at: root) }
        let peer = try Self.enrol(bench)
        let (_, real) = try await Self.announce(bench, peer, Self.gcode)
        let madeUp = "QRSTUVWXYZ234567"
        #expect(real != madeUp)
        let port = bench.port
        let declared = Self.hexSha(Self.gcode)
        /// Only the status line and the body: the rest is the same server's headers.
        func answer(_ id: String, _ headers: (String) -> [String: String]) async -> String {
            let path = "\(Self.slices)/\(id)/file"
            let head = Self.gibHead(path, headers: headers(path))
            let raw = await offPool { Self.raw(port: port, head) }
            let status = raw.components(separatedBy: "\r\n").first ?? ""
            let body = raw.components(separatedBy: "\r\n\r\n").dropFirst().joined()
            return status + " " + body
        }
        let ways: [(String, (String) -> [String: String])] = [
            ("unsigned", { _ in [LanServer.connectorHashHeader: declared] }),
            ("forged", { path in
                var h = peer.headers("PUT", path, bodyHash: declared)
                h[LanServer.connectorHashHeader] = declared
                h["x-khayt-mac"] = Data(repeating: 7, count: 32).base64EncodedString()
                return h }),
            ("signed over another hash", { path in
                var h = peer.headers("PUT", path, bodyHash: String(repeating: "b", count: 64))
                h[LanServer.connectorHashHeader] = declared
                return h }),
            ("stranger", { path in
                var h = Peer(id: "dev_NotEnrolledAtAll12", key: Data(repeating: 1, count: 32))
                    .headers("PUT", path, bodyHash: declared)
                h[LanServer.connectorHashHeader] = declared
                return h }),
        ]
        for (name, headers) in ways {
            let forReal = await answer(real, headers)
            let forNone = await answer(madeUp, headers)
            #expect(forReal.hasPrefix("HTTP/1.1 401"), Comment(rawValue: "\(name): \(forReal)"))
            #expect(forReal == forNone, Comment(rawValue: "\(name): real \(forReal) vs made-up \(forNone)"))
        }
        // None of it touched the slice: it still takes its file.
        #expect(try await Self.put(bench, peer, real, Self.gcode).status == 201)
    }

    @Test("over the Mac's own cap: refused at the announce, and 413 from a file's head")
    func overTheCap() async throws {
        let (bench, root) = try await Self.bench(maxBytes: 64)
        defer { bench.stop(); try? FileManager.default.removeItem(at: root) }
        let peer = try Self.enrol(bench)
        let (announced, _) = try await Self.announce(bench, peer, Self.gcode)
