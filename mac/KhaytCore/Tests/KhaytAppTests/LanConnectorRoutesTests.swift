/// A paired slicer plugin's own routes (`LanServer+Connector`), through a real
/// listener on the bench: who may ask, the capture sealed and checked by the
/// shared rule (`lib/connector-slice.js` in the engine), the file judged at
/// its head and hashed as it lands, the answers signed back — and the book
/// untouched throughout (inbox-first).
@MainActor
@Suite(.serialized)
struct LanConnectorRoutesTests {

    static let pin = "24682468"
    /// `LanServerTests.Bench.start`, as a number nothing has to hop to the main actor for.
    nonisolated static let now = 1_800_000_000
    nonisolated static let slices = "/api/connectors/slices"

    // MARK: - Helpers

    struct Peer {
        let id: String
        let key: Data
        /// Sign a request; `bodyHash` stands for a body not sent yet (a file head).
        func headers(_ method: String, _ target: String, body: Data = Data(), bodyHash: String? = nil)
            -> [String: String] {
            let nonce = Data((0..<16).map { _ in UInt8.random(in: 0...255) }).map { String(format: "%02x", $0) }.joined()
            let canonical = LanDevices.canonical(method: method, target: target, time: String(LanConnectorRoutesTests.now),
                                                 nonce: nonce, body: body, bodyHash: bodyHash)
            return ["x-khayt-device": id, "x-khayt-time": String(LanConnectorRoutesTests.now), "x-khayt-nonce": nonce,
                    "x-khayt-mac": LanDevices.mac(key: key, canonical: canonical).base64EncodedString()]
        }
    }

    static func enrol(_ bench: LanServerTests.Bench, kind: String? = LanDevices.kindConnector,
                      name: String = "OrcaSlicer on the PC") throws -> Peer {
        let s = try LanConnectorScopeTests.enrol(bench.devices, kind: kind, name: name)
        return Peer(id: s.id, key: s.key)
    }

    static func scratch() -> URL {
        FileManager.default.temporaryDirectory
            .appending(path: "khayt-connector-test-\(UUID().uuidString)", directoryHint: .isDirectory)
    }

    static func bench(enabled: Bool = true, maxBytes: Int = LanServer.maxInflate)
        async throws -> (LanServerTests.Bench, URL) {
        let root = scratch()
        let bench = try await LanServerTests.Bench(pin: pin, slicerRoot: root, slicerMaxBytes: maxBytes,
                                                   connectorsEnabled: enabled)
        return (bench, root)
    }

    static func hexSha(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }

    static let gcode = Data("""
        ; generated by OrcaSlicer 2.5.1
        ; estimated printing time (normal mode) = 1h 2m 5s
        ; filament used [g] = 12.34
        ; filament_type = PLA
        G28
        G1 X10 Y10 Z0.2 F3000
        G1 X20 Y10 E1.2

        """.utf8)

    static func capture(_ file: Data, name: String = "Bracket_PLA.gcode", intent: String = "inbox",
                        extra: String = "") -> Data {
        let sha = hexSha(file)
        return Data(#"""
            {"v":1,"kind":"slice","id":"0b6f1d2e3c4a5b6c","idem":"sha256:\#(sha)","intent":"\#(intent)",\#(extra)
             "file":{"name":"\#(name)","bytes":\#(file.count),"sha256":"\#(sha)","type":"gcode"},
             "slicer":{"name":"OrcaSlicer","version":"2.5.1","plugin":"0.1.0"},
             "filaments":[{"slot":1,"type":"PLA","colour":"#FFFFFF","grams":12.34}]}
            """#.utf8)
    }

    static func sealed(_ plain: Data, for peer: Peer, method: String = "POST", path: String = slices) -> Data {
        LanServer.seal(plain, key: LanServer.sealKey(peer.key, connectorId: peer.id),
                       aad: LanServer.sealAad(method: method, path: path))!
    }

    static func call(_ bench: LanServerTests.Bench, _ peer: Peer, _ method: String, _ path: String,
                     body: Data = Data(), extra: [String: String] = [:]) async throws -> LanServerTests.Bench.Reply {
        var headers = peer.headers(method, path, body: body)
        for (k, v) in extra { headers[k] = v }
        return try await bench.send(method, path, body: body.isEmpty ? nil : body, headers: headers, timeout: 30)
    }

    /// Announce, and the slice id it was given.
    static func announce(_ bench: LanServerTests.Bench, _ peer: Peer, _ file: Data,
                         intent: String = "inbox") async throws -> (LanServerTests.Bench.Reply, String) {
        let reply = try await call(bench, peer, "POST", slices, body: sealed(capture(file, intent: intent), for: peer))
        return (reply, (reply.json["sliceId"] as? String) ?? "")
    }

    static func put(_ bench: LanServerTests.Bench, _ peer: Peer, _ sliceId: String, _ bytes: Data,
                    declared: String? = nil) async throws -> LanServerTests.Bench.Reply {
        let path = "\(slices)/\(sliceId)/file"
        let hash = declared ?? hexSha(bytes)
        var headers = peer.headers("PUT", path, bodyHash: hash)
        headers[LanServer.connectorHashHeader] = hash
        headers["Content-Type"] = "application/octet-stream"
        return try await bench.send("PUT", path, body: bytes, headers: headers, timeout: 30)
    }

    /// The answer was signed by the key the plugin holds.
    static func signedBy(_ reply: LanServerTests.Bench.Reply, _ peer: Peer, nonce: String) -> Bool {
        reply.headers["x-khayt-reply-mac"] == LanServer.replyMac(key: peer.key, nonce: nonce, status: reply.status,
                                                                 body: reply.body)
    }

    /// Send a raw head (no body), return everything that comes back.
    nonisolated static func raw(port: UInt16, _ text: String) -> String {
        let fd = socket(AF_INET, SOCK_STREAM, 0)
        guard fd >= 0 else { return "no socket" }
        defer { close(fd) }
        var addr = sockaddr_in()
        addr.sin_family = sa_family_t(AF_INET)
        addr.sin_port = port.bigEndian
        addr.sin_addr.s_addr = inet_addr("127.0.0.1")
        let ok = withUnsafePointer(to: &addr) {
            $0.withMemoryRebound(to: sockaddr.self, capacity: 1) { connect(fd, $0, socklen_t(MemoryLayout<sockaddr_in>.size)) }
        }
        guard ok == 0 else { return "no connect" }
        let data = Data(text.utf8)
        _ = data.withUnsafeBytes { write(fd, $0.baseAddress, data.count) }
        var tv = timeval(tv_sec: Int(LanStallTests.patience), tv_usec: 0)
        setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &tv, socklen_t(MemoryLayout<timeval>.size))
        var got = Data()
        var buf = [UInt8](repeating: 0, count: 4096)
        while got.count < 16_384 {
            let n = read(fd, &buf, buf.count)
            guard n > 0 else { break }
            got.append(contentsOf: buf[0..<n])
            if let text = String(data: got, encoding: .utf8), text.contains("\r\n\r\n"), text.hasSuffix("}") { break }
        }
        return String(decoding: got, as: UTF8.self)
    }

    /// A PUT head declaring a GiB, of which nothing is ever sent.
    nonisolated static func gibHead(_ path: String, headers: [String: String]) -> String {
        var text = "PUT \(path) HTTP/1.1\r\nHost: 127.0.0.1\r\nContent-Type: application/octet-stream\r\n"
            + "Content-Length: \(1 << 30)\r\nExpect: 100-continue\r\n"
        for (k, v) in headers { text += "\(k): \(v)\r\n" }
        return text + "\r\n"
    }

    // MARK: - Shared vectors

    struct Vectors: Decodable {
        struct Req: Decodable { let name, keyHex, method, target, time, nonce, bodyB64, bodyHash, canonical, mac: String }
        struct Rep: Decodable { let name, keyHex, nonce, bodyB64, mac: String; let status: Int }
        struct Seal: Decodable {
            let name, keyHex, connectorId, sealKeyHex, method, path, aad, nonceB64, plainB64, ctB64: String
        }
        let request: [Req]
        let reply: [Rep]
        let seal: [Seal]
    }

    @Test("the declared-hash signature, the reply MAC and the seal match the shared vectors byte for byte")
    func vectors() throws {
        let url = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
            .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("docs/connector-routes.vectors.json")
        let v = try JSONDecoder().decode(Vectors.self, from: Data(contentsOf: url))
        #expect(v.request.count >= 3 && v.reply.count >= 3 && v.seal.count >= 3)
        for c in v.request {
            let body = try #require(Data(base64Encoded: c.bodyB64))
            #expect(Self.hexSha(body) == c.bodyHash, "\(c.name)")
            let declared = LanDevices.canonical(method: c.method, target: c.target, time: c.time, nonce: c.nonce,
                                                body: Data(), bodyHash: c.bodyHash)
            #expect(declared == c.canonical, "\(c.name)")
            // The same canonical as hashing the body itself: one signature, whichever way it is checked.
            #expect(LanDevices.canonical(method: c.method, target: c.target, time: c.time, nonce: c.nonce, body: body)
                    == c.canonical, "\(c.name)")
            #expect(LanDevices.mac(key: LanConnectorPairingTests.hex(c.keyHex), canonical: c.canonical)
                .base64EncodedString() == c.mac, "\(c.name)")
        }
        for c in v.reply {
            #expect(LanServer.replyMac(key: LanConnectorPairingTests.hex(c.keyHex), nonce: c.nonce, status: c.status,
                                       body: try #require(Data(base64Encoded: c.bodyB64))) == c.mac, "\(c.name)")
        }
        for c in v.seal {
            let key = LanServer.sealKey(LanConnectorPairingTests.hex(c.keyHex), connectorId: c.connectorId)
            #expect(key.withUnsafeBytes { Data($0) } == LanConnectorPairingTests.hex(c.sealKeyHex), "\(c.name)")
            let aad = LanServer.sealAad(method: c.method, path: c.path)
            #expect(String(decoding: aad, as: UTF8.self) == c.aad)
            let plain = try #require(Data(base64Encoded: c.plainB64))
            let nonce = try AES.GCM.Nonce(data: try #require(Data(base64Encoded: c.nonceB64)))
            let envelope = try #require(LanServer.seal(plain, key: key, aad: aad, nonce: nonce))
            let e = try #require(try JSONSerialization.jsonObject(with: envelope) as? [String: Any])
            #expect(e["ct"] as? String == c.ctB64, "\(c.name)")
            #expect(e["nonce"] as? String == c.nonceB64)
            let theirs = Data(#"{"v":1,"alg":"A256GCM","nonce":"\#(c.nonceB64)","ct":"\#(c.ctB64)"}"#.utf8)
            #expect(LanServer.unseal(theirs, key: key, aad: aad) == plain, "\(c.name)")
            #expect(LanServer.unseal(theirs, key: key, aad: Data("PUT /elsewhere".utf8)) == nil, "bound to its route")
        }
    }

