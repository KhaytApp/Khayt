  $('#poSection')?.addEventListener('click', async (e) => {
    const loadMorePos = e.target.closest('[data-act="load-more-pos"]');
    if (loadMorePos) { poDisplayLimit += 50; renderPurchaseOrders(); return; }
    const recv    = e.target.closest('[data-act="po-receive"]');
    const del     = e.target.closest('[data-act="po-del"]');
    const closePo = e.target.closest('[data-act="po-close"]');

    // Correct one PO priced per spool instead of per gram. Owner-initiated and
    // confirmed: the order may already be with a supplier, so the amount is
    // never rewritten without someone looking at both figures. Undoable.
    const fixPrice = e.target.closest('[data-act="po-fix-price"]');
    if (fixPrice) {
      const suspects = KhaytPoAudit.findSuspectPurchaseOrders(purchaseOrders, inventory);
      const entry = suspects.find((x) => x.po.id === fixPrice.dataset.id);
      if (!entry) { renderPurchaseOrders(); return; }
      const cur = (typeof currencySymbol === 'function') ? currencySymbol() : '';
      const money = (v) => `${fmtMoney(v)}${cur ? ' ' + cur : ''}`;
      const okToFix = await confirmModal(
        (t('po.fix_confirm') || 'Change this order from {was} to {now}?')
          .replace('{was}', money(entry.currentTotal))
          .replace('{now}', money(entry.suggestedTotal)),
        { danger: false },
      );
      if (!okToFix) return;
      const before = entry.po.unitPrice;
      const res = KhaytPoAudit.applyCorrection(entry);
      if (!res.ok) { toast(res.error, 'error'); return; }
      saveAll();
      renderPurchaseOrders();
      toast(t('po.fix_done') || 'Purchase order corrected', 'success', 6000, {
        undo: () => { entry.po.unitPrice = before; saveAll(); renderPurchaseOrders(); },
      });
      return;
    }

    if (recv) {
      const po = purchaseOrders.find(p => p.id === recv.dataset.id);
      if (!po) return;
      // A consumable order is counted in the shop's own unit. Everything below —
      // the amount asked for, the field restocked, the expense category, the
      // toast — differs by kind, and a PO written before consumables could be
      // ordered has no `kind` at all, so absent reads as filament.
      const isCons = po.kind === 'consumable';
      const unitLbl = isCons ? ((po.unit || '').trim() || (t('cons.unit') || 'units')) : 'g';
      const alreadyReceived = po.receivedSoFar || 0;
      // `qty` is the only quantity a purchase order carries — grams for filament,
      // the shop's own unit for a consumable. `weightOrdered` was read here from
      // the day this dialog was written and has never been written by any version
      // of createPurchaseOrder, so a filament order measured itself against 0:
      // the box offered a flat 1000 g and the order could never reach `received`.
      const ordered = +po.qty || 0;
      const remaining = ordered > 0 ? ordered - alreadyReceived : (isCons ? 1 : 1000);
      openFormModal({
        title: t('po.receive'),
        sizeLg: false,
        saveLabel: t('po.receive'),
        bodyHtml: `
          <label>${escapeHtml(isCons ? `${t('po.qty_received') || 'Quantity received'} (${unitLbl})` : t('po.weight_received'))}</label>
          <input type="number" id="poRecvWeight" value="${Math.max(0, remaining)}" min="0" step="${isCons ? '0.01' : '1'}">
          <label style="margin-top:12px;">${escapeHtml(t('po.notes'))}</label>
          <input type="text" id="poRecvNotes" placeholder="${escapeHtml(t('po.notes'))}">`,
        async onSave(modal) {
          const w = Math.max(0, num(modal.querySelector('#poRecvWeight').value, 0));
          if (w <= 0) { toast(t('exp.amount_required') || 'Enter a weight', 'error'); return false; }
          const notes = modal.querySelector('#poRecvNotes').value.trim();
          if (isCons) {
            // Restock the consumable, not a spool. Looking this up in `inventory`
            // would find nothing, restock nothing, and still mark the order
            // received — goods paid for and silently absent from stock.
            const cons = consumables.find(x => x.id === po.itemId);
            if (cons) {
              cons.stock = Math.max(0, (+cons.stock || 0) + w);   // no 99000 cap; that is a spool's
              renderConsumables();
            }
          } else {
            const invItem = inventory.find(i => i.id === po.itemId);
            if (invItem) {
              invItem.weight = Math.min((invItem.weight || 0) + w, 99000);
              if (!invItem.usageHistory) invItem.usageHistory = [];
              invItem.usageHistory.unshift({ type: 'received', orderId: po.id, weightUsed: -w, date: localDateStr(), notes });
              if (invItem.usageHistory.length > 200) invItem.usageHistory.length = 200;
              renderInventory();
            }
          }
          po.receivedSoFar = alreadyReceived + w;
          if (ordered > 0 && po.receivedSoFar >= ordered) {
            po.status = 'received';
            po.receivedAt = localDateStr();
            toast(t('po.received_toast') + ' · +' + w + unitLbl, 'success');
          } else {
            po.status = 'partial';
            toast(t('po.partial') + ' · +' + w + unitLbl, 'success');
          }
          // Automatically create an expense record for the received goods.
          //
          // A purchase order prices itself one way and one way only: `unitPrice`
          // against `qty`, per gram for filament and per unit of the shop's own
          // for a consumable. Both therefore multiply out identically and there
          // is no /1000 — the per-KILO rate that division assumed lived in
          // `unitCost`, which, like `totalCost`, no version of the app has ever
          // written. Every filament receipt booked nothing at all: the spool was
          // paid for and absent from the material spend that pricing and the
          // per-kilo analytics are derived from.
          const unitPrice = +po.unitPrice || 0;
          if (unitPrice > 0) {
            const expAmount = +(w * unitPrice).toFixed(2);
            if (expAmount > 0) {
              expenses.push({
                id:       uid('EXP'),
                date:     localDateStr(),
                amount:   expAmount,
                // Glue and bags are not filament. Booking them there inflates the
                // material spend that feeds pricing and the per-kilo figures in
                // analytics. There is no consumables category, so `other` — which
                // is merely unspecific, where `filament` would be wrong.
                category: isCons ? 'other' : 'filament',
                note:     `${t('po.receive') || 'PO receive'}: ${po.id}${notes ? ' — ' + notes : ''}`,
                orderId:  null,
                poId:     po.id,
              });
              renderExpenses?.();
            }
          }
          saveAll();
          renderPurchaseOrders();
          return true;
        }
      });
    }
    if (closePo) {
      const po = purchaseOrders.find(p => p.id === closePo.dataset.id);
      if (po) {
        po.status = 'received';
        po.receivedAt = localDateStr();
        saveAll();
        renderPurchaseOrders();
        toast(t('po.received_toast'), 'success');
      }
    }
    if (del) {
      const ok = await confirmModal(t('common.delete') + '?', { danger: true });
      if (!ok) return;
      purchaseOrders = purchaseOrders.filter(p => p.id !== del.dataset.id);
      saveAll();
      renderPurchaseOrders();
    }
    const recInv = e.target.closest('[data-act="po-record-invoice"]');
    if (recInv) recordSupplierInvoice(recInv.dataset.id);
  });

