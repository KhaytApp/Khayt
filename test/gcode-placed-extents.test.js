'use strict';
/**
 * lib/gcode-placed-extents.js: where a G-code file's models sit on the bed,
 * from the slicer's own object list, so lib/send-checks.js can say "Fits the
 * bed" or block a send that cannot fit. Synthetic files only: the marker lines
 * are the slicers' documented shapes (Klipper EXCLUDE_OBJECT_DEFINE,
 * PrusaSlicer objects_info, Orca max_z_height, PrusaSlicer max_layer_z, Cura
 * ;MAXZ). Timed at 8 MB, adversarial inputs included, and loaded the way
 * JavaScriptCore loads it.
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const vm = require('node:vm');
const P = require('../lib/gcode-placed-extents.js');

const ms = (f) => { const t = process.hrtime.bigint(); f(); return Number(process.hrtime.bigint() - t) / 1e6; };
const moves = (n) => {
  const out = [];
  for (let i = 0; i < n; i++) out.push(`G1 X${(100 + (i % 50)).toFixed(3)} Y${(100 + (i % 37)).toFixed(3)} E0.0123`);
  return out.join('\n');
};
const ORCA = [
  '; generated by OrcaSlicer 2.3.4',
  '; max_z_height: 42.20',
  'EXCLUDE_OBJECT_DEFINE NAME=Cube_id_0_copy_0 CENTER=60,60 POLYGON=[[40,40],[80,40],[80,80],[40,80],[40,40]]',
  'EXCLUDE_OBJECT_DEFINE NAME=Clip_id_1_copy_0 CENTER=200,150 POLYGON=[[180.5,120],[220.25,120],[220.25,180],[180.5,180]]',
  'G1 Z.2 F720',
  ';TYPE:Skirt',
  'G1 X5 Y5 E1',          // a purge line far outside the models: not a placed extent
  'G1 X250 Y5 E5',
].join('\n');

test('Klipper object list: the outlines as placed, the height from the slicer', () => {
  const r = P.placedExtents(ORCA);
  assert.deepEqual(r, { x: 180.3, y: 140, z: 42.2, min: { x: 40, y: 40 }, max: { x: 220.3, y: 180 },
    source: 'placed-extents', from: 'exclude-object', objects: 2 });
});

test('PrusaSlicer objects_info, with max_layer_z from its config block', () => {
  const info = { objects: [{ name: 'a', polygon: [[10, 20], [110, 20], [110, 70], [10, 70]] }, { name: 'b', polygon: [[150, 150], [160, 160]] }] };
  const text = ['; generated by PrusaSlicer 2.8.1', `; objects_info = ${JSON.stringify(info)}`, moves(10), '; max_layer_z = 12.6'].join('\n');
  const r = P.placedExtents(text);
  assert.equal(r.source, 'placed-extents');
  assert.equal(r.from, 'objects-info');
  assert.deepEqual([r.x, r.y, r.z, r.objects], [150, 140, 12.6, 2]);
});

test('no object list: the extruding moves, labelled toolpath (send-checks only warns on it)', () => {
  const r = P.placedExtents([';MAXZ:3.2', 'G90', 'M83', 'G1 Z0.2', 'G1 X10 Y10 E1', 'G1 X60 Y30 E1'].join('\n'));
  assert.equal(r.source, 'toolpath');
  assert.equal(r.from, 'moves');
  assert.equal(r.z, 3.2);
  assert.ok(r.x > 0 && r.y > 0);
  assert.equal(P.placedExtents('G1 X10 Y10 E1', { moves: false }), null, 'moves can be refused');
});

test('nothing to read, junk, and markers mid-line are not taken', () => {
  for (const t of ['', null, undefined, 42, '; hello', 'EXCLUDE_OBJECT_DEFINE NAME=x POLYGON=[[1,2],', 'EXCLUDE_OBJECT_DEFINE POLYGON=nope']) {
    const r = P.placedExtents(t, { moves: false });
    assert.equal(r, null, JSON.stringify(t));
  }
  // A comment that merely mentions the command is not an object.
  assert.equal(P.placedExtents('; see EXCLUDE_OBJECT_DEFINE POLYGON=[[0,0],[999,999]]', { moves: false }), null);
  // A non-number point is skipped, the rest still count.
  const r = P.placedExtents('EXCLUDE_OBJECT_DEFINE NAME=a POLYGON=[[0,0],["x",5],[10,10]]');
  assert.deepEqual([r.x, r.y], [10, 10]);
});

test('8 MB of ordinary G-code with an object list: fast', () => {
  const big = ORCA + '\n' + moves(320000);
  assert.ok(big.length > 8 * 1024 * 1024, `${big.length}`);
  let r;
  const t = ms(() => { r = P.placedExtents(big); });
  assert.equal(r.source, 'placed-extents');
  assert.ok(t < 500, `took ${t} ms`);
});

test('8 MB with no object list (the moves fallback): within a second', () => {
  const big = '; max_layer_z = 5\nM83\n' + moves(330000);
  const t = ms(() => P.placedExtents(big));
  assert.ok(t < 1500, `took ${t} ms`);
});

test('hostile: 8 MB of markers with no newline, or a giant unterminated list, stays linear', () => {
  for (const s of [
    'EXCLUDE_OBJECT_DEFINE '.repeat(400000),
    '\nEXCLUDE_OBJECT_DEFINE POLYGON=' + '['.repeat(8 * 1024 * 1024),
    '; objects_info = {' + '"a":'.repeat(2000000),
    '; max_z_height:'.repeat(500000),
    'EXCLUDE_OBJECT_DEFINE NAME=a POLYGON=[[1,2]]\n'.repeat(200000),
  ]) {
    const t = ms(() => P.placedExtents(s, { moves: false }));
    assert.ok(t < 1000, `took ${t} ms on ${s.slice(0, 30)}…`);
  }
  // The object cap holds: 200 000 outlines read as at most MAX_OBJECTS.
  const r = P.placedExtents('EXCLUDE_OBJECT_DEFINE NAME=a POLYGON=[[1,2],[3,4]]\n'.repeat(5000));
  assert.ok(r.objects <= P.MAX_OBJECTS);
});

test('loads without require, as JavaScriptCore loads it, with gcode-geometry beside it', () => {
  const ctx = {}; vm.createContext(ctx);
  for (const f of ['gcode-geometry', 'gcode-placed-extents']) vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'lib', f + '.js'), 'utf8'), ctx);
  ctx.ORCA = ORCA;
  assert.equal(vm.runInContext('KhaytGcodePlacedExtents.placedExtents(ORCA).x', ctx), 180.3);
  assert.equal(vm.runInContext("KhaytGcodePlacedExtents.placedExtents('M83\\nG1 Z0.2\\nG1 X1 Y1 E1\\nG1 X21 Y11 E1').source", ctx), 'toolpath');
});

test('send-checks reads it: fits, does not fit (block), and toolpath only warns', () => {
  const SC = require('../lib/send-checks.js');
  const machine = (x, y, z) => ({ model: 'U1', bed: { x, y, z }, printerApi: { type: 'moonraker' } });
  const codes = (file, m) => SC.sendChecks(file, m, []).map((f) => `${f.code}:${f.severity}`);
  const bounds = P.placedExtents(ORCA);
  assert.deepEqual(codes({ name: 'a.gcode', bounds }, machine(270, 270, 270)).filter((c) => c.startsWith('bed-')), [], 'fits the bed');
  assert.ok(codes({ name: 'a.gcode', bounds }, machine(150, 150, 270)).includes('bed-footprint:block'), 'too big: blocked');
  assert.ok(codes({ name: 'a.gcode', bounds }, machine(270, 270, 40)).includes('bed-height:block'), 'too tall: blocked');
  const tp = P.placedExtents('M83\nG1 Z0.2\nG1 X0 Y0 E1\nG1 X300 Y10 E1');
  assert.ok(codes({ name: 'a.gcode', bounds: tp }, machine(250, 250, 250)).some((c) => c.endsWith(':warn')), 'toolpath: a warning, never a block');
});
