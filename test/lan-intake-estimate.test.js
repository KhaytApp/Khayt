test('an oversized body is cut off rather than buffered', async () => {
  // 32 MB cap. Sending 40 MB must not be held in memory to completion.
  const big = Buffer.alloc(40 * 1024 * 1024, 0x41);
  let status = 0;
  try {
    const r = await estimate('huge.stl', big);
    status = r.status;
  } catch (e) {
    // A destroyed socket surfaces as a fetch failure, which is the intended
    // outcome — the point is that it did not succeed.
    status = 413;
  }
  assert.ok(status === 413 || status >= 400, `expected a refusal, got ${status}`);
});

test('a visitor who hammers the endpoint is rate limited', async () => {
  // Each request parses a mesh, so this is the guard that stops one visitor
  // pinning the shop's machine.
  const saved = store.settings.lanApi.intakeQuote.hourlyLimit;
  store.settings.lanApi.intakeQuote.hourlyLimit = 1;
  try {
    // The window counter is shared with the rest of the suite, so the very next
    // request is already over a limit of one.
    const r = await estimate('part.3mf', slicedZip());
    assert.equal(r.status, 429);
    const b = await r.json();
    assert.match(b.error, /Too many/);
  } finally {
    store.settings.lanApi.intakeQuote.hourlyLimit = saved;
  }
});

/**
 * Concurrency, which the hourly limit does not bound.
 *
 * The per-IP hourly limit answers "how often", never "how many at once", and
 * the two are not the same bound: twenty simultaneous uploads is 640 MB held in
 * the main process while every one of them is still inside its allowance. It is
 * also the only one of the three limits on this route that a caller cannot move,
 * because it is keyed on nothing — behind the tunnel the per-IP key is the
 * caller's own X-Forwarded-For header.
 */
test('only so many uploads may be in flight at once, and a slot comes back', async () => {
  const http = require('node:http');
  // Announce a body far larger than we send, so the server sits waiting for the
  // rest and the slot stays taken while we probe.
  const holdOpen = () => new Promise((resolve) => {
    const req = http.request({
      host: '127.0.0.1', port: PORT, method: 'POST',
      path: '/api/intake/estimate?name=held.stl',
      headers: {
        'content-type': 'application/octet-stream',
        'x-khayt-intake-token': 'tok',
        'content-length': '4096',
      },
    });
    req.on('error', () => {});
    req.write(Buffer.alloc(16, 0x41), () => resolve(req));
  });

  const held = [];
  for (let i = 0; i < 3; i++) held.push(await holdOpen());
  try {
    // Poll rather than assume the three are parked: the writes have flushed but
    // the server reaching the slot check is a separate turn of the loop.
    let res = null;
    for (let i = 0; i < 40 && !(res && res.status === 503); i++) {
      res = await estimate('probe.stl', Buffer.alloc(64, 0x41));
      if (res.status !== 503) await new Promise((r) => setTimeout(r, 25));
    }
    assert.equal(res.status, 503, 'a fourth concurrent upload should be turned away');
    const b = await res.json();
    assert.equal(b.reason, 'busy');
    assert.equal(b.price, undefined, 'and a refusal still leaks no number');
  } finally {
    for (const r of held) r.destroy();
  }

  // Slots are released on response close, including the sockets we just killed
  // mid-upload — otherwise one abandoned upload would retire a slot for good.
  let after = null;
  for (let i = 0; i < 40; i++) {
    after = await estimate('part.3mf', slicedZip());
    if (after.status === 200) break;
    await new Promise((r) => setTimeout(r, 25));
  }
  assert.equal(after.status, 200, 'an abandoned upload must not retire its slot permanently');
});

/*
 * Break-risk on a stranger's upload.
 *
 * This is the placement where the triage is worth most: the shop is deciding
 * whether to take a job at a price a customer has ALREADY been shown, and "a
 * fifth of this needs supports" is exactly what turns an acceptable price into
 * an unacceptable one.
 *
 * And it is the placement where the answer must not go back out. The visitor
 * gets a price. Whether the model needs supports is the shop's call, not an
 * argument to have with someone who cannot act on it — so the reply to the
 * browser stays exactly as it was.
 */

/** A binary STL of a cube held up over a small pad: a real 100 mm² ceiling. */
function bridgeStl() {
  const tri = (a, b, c) => [a, b, c];
  const boxTris = (x0, y0, z0, x1, y1, z1) => {
    const v = [
      [x0, y0, z0], [x1, y0, z0], [x1, y1, z0], [x0, y1, z0],
      [x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1],
    ];
    const q = (a, b, c, d) => [tri(v[a], v[b], v[c]), tri(v[a], v[c], v[d])];
    return [...q(0, 3, 2, 1), ...q(4, 5, 6, 7), ...q(0, 1, 5, 4),
            ...q(2, 3, 7, 6), ...q(1, 2, 6, 5), ...q(0, 4, 7, 3)];
  };
  const tris = [...boxTris(0, 0, 0, 2, 2, 1), ...boxTris(0, 0, 8, 10, 10, 10)];
  const buf = Buffer.alloc(84 + tris.length * 50);
  buf.writeUInt32LE(tris.length, 80);
  let off = 84;
  for (const t of tris) {
    off += 12;                                   // normal, which parseStl ignores
    for (const p of t) for (const n of p) { buf.writeFloatLE(n, off); off += 4; }
    off += 2;                                    // attribute bytes
  }
  return buf;
}

test('a customer upload is analysed for the shop, and the visitor is told only the price', async () => {
  const res = await estimate('part.stl', bridgeStl());
  const body = await res.json();
  assert.equal(body.ok, true, JSON.stringify(body));
  assert.ok(body.price > 0);
  // The whole point: nothing about the mesh comes back out.
  assert.equal(body.risk, undefined, 'the print-risk report was sent to the visitor');
  assert.deepEqual(
    Object.keys(body).sort(),
    ['binding', 'currency', 'exact', 'grams', 'hours', 'ok', 'price', 'qty', 'ref', 'slicer'].sort(),
    'the public reply grew a field — anything added here is visible to strangers',
  );

  // …and the shop sees it when the request lands in front of them.
  const before = store.waitingList.length;
  const r = await fetch(`${BASE}/api/intake`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'x-khayt-intake-token': 'tok' },
    body: JSON.stringify({
      name: 'A Customer', description: 'Print this please', consent: true, estimateRef: body.ref,
    }),
  });
  assert.equal(r.status, 200, await r.text());
  assert.equal(store.waitingList.length, before + 1);

  const entry = store.waitingList[store.waitingList.length - 1];
  const risk = entry.modelQuote && entry.modelQuote.risk;
  assert.ok(risk, 'the shop was given no triage for a model with a 100 mm² ceiling');
  const ids = risk.risks.map((x) => x.id);
  assert.ok(ids.includes('overhang'), `expected an overhang finding, got ${JSON.stringify(ids)}`);
  assert.ok(ids.includes('bridge'), 'a flat ceiling was not reported as a bridge');
  // The measurement travels with it, or the shop cannot judge it.
  const over = risk.risks.find((x) => x.id === 'overhang');
  assert.ok(over.fraction > 0, 'the finding arrived without its measurement');
  assert.equal(over.thresholdDeg, 45);
});

