/**
 * POST /api/intake/estimate — pricing a model a stranger uploaded.
 *
 * This is the only route in Khayt that hands a price to someone who is not the
 * shop, and the only public one that accepts a body measured in megabytes. So
 * these tests boot the real server and speak HTTP to it: asserting against
 * lib/public-quote.js directly would prove the arithmetic (already covered) and
 * nothing about the auth, the limits, or what happens when the body is hostile.
 */
