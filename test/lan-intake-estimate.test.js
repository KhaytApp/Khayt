test('quantity is honoured and bounded', async () => {
  const one = await (await estimate('p.3mf', slicedZip())).json();
  const four = await (await estimate('p.3mf', slicedZip(), { qty: 4 })).json();
  assert.equal(four.qty, 4);
  assert.ok(four.price > one.price);
  const silly = await (await estimate('p.3mf', slicedZip(), { qty: 999999 })).json();
  assert.equal(silly.qty, 1000, 'clamped');
});

test('the estimate attached to a submitted request is the SERVER\'s, not the browser\'s', async () => {
  // A browser can post any number it likes. The shop must see what we actually
  // said, so the submission cites a reference and we look it up.
  const est = await (await estimate('part.3mf', slicedZip())).json();
  assert.ok(est.ok && est.ref);

  const before = store.waitingList.length;
  const r = await fetch(`${BASE}/api/intake`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', 'x-khayt-intake-token': 'tok' },
    body: JSON.stringify({
      name: 'A Customer', description: 'Please print this bracket', consent: true,
      estimateRef: est.ref,
      // The lie a hostile browser would tell:
      estValue: 999999, modelQuote: { price: 1, exact: true },
    }),
  });
  assert.equal(r.status, 200, await r.text());
  assert.equal(store.waitingList.length, before + 1);
  const entry = store.waitingList[store.waitingList.length - 1];
  assert.equal(entry.estValue, est.price, 'our figure, not theirs');
  assert.equal(entry.modelQuote.price, est.price);
  assert.equal(entry.modelQuote.exact, true);
  assert.equal(entry.modelQuote.binding, false);
});

