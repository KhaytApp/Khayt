const PRUSA_CFG = [
  '; generated by PrusaSlicer 2.8.0',
  '; estimated printing time (normal mode) = 3h 12m 40s',
  '; filament used [g] = 41.83',
  '; filament_type = PLA',
].join('\n');

const TETRA = '<?xml version="1.0"?><model unit="millimeter"><resources>'
  + '<object id="1" type="model"><mesh><vertices>'
  + '<vertex x="0" y="0" z="0"/><vertex x="60" y="0" z="0"/>'
  + '<vertex x="0" y="60" z="0"/><vertex x="0" y="0" z="60"/>'
  + '</vertices><triangles>'
  + '<triangle v1="0" v2="2" v3="1"/><triangle v1="0" v2="1" v3="3"/>'
  + '<triangle v1="0" v2="3" v3="2"/><triangle v1="1" v2="2" v3="3"/>'
  + '</triangles></mesh></object></resources>'
  + '<build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 0 0 0"/></build></model>';

const slicedZip = () => writeZip([
  { name: '3D/3dmodel.model', data: Buffer.from(TETRA, 'utf8') },
  { name: 'Metadata/Slic3r_PE.config', data: Buffer.from(PRUSA_CFG, 'utf8') },
]);
const unslicedZip = () => writeZip([{ name: '3D/3dmodel.model', data: Buffer.from(TETRA, 'utf8') }]);

/** POST a model. Authenticates with the intake token, as the form's session does. */
const estimate = (name, body, opts = {}) => fetch(
  `${BASE}/api/intake/estimate?name=${encodeURIComponent(name)}${opts.qty ? `&qty=${opts.qty}` : ''}`,
  {
    method: 'POST',
    headers: {
      'content-type': 'application/octet-stream',
      ...(opts.noAuth ? {} : { 'x-khayt-intake-token': 'tok' }),
    },
    body,
  });

test('a sliced model comes back priced, and named as the slicer\'s figures', async () => {
  const r = await estimate('part.3mf', slicedZip());
  assert.equal(r.status, 200);
  const b = await r.json();
  assert.equal(b.ok, true, JSON.stringify(b));
  assert.equal(b.exact, true);
  assert.equal(b.slicer, 'PrusaSlicer');
  assert.ok(b.price > 0);
  assert.equal(b.currency, 'SAR');
  assert.ok(b.ref, 'a reference is issued so the submission can cite it');
  assert.equal(b.binding, false, 'and it is never a binding quote');
  // 41.83 g plus the shop's 3% waste.
  assert.ok(Math.abs(b.grams - 41.83 * 1.03) < 0.2, `grams was ${b.grams}`);
});

test('an unsliced model is priced but flagged as an estimate', async () => {
  const b = await (await estimate('raw.3mf', unslicedZip())).json();
  assert.equal(b.ok, true, JSON.stringify(b));
  assert.equal(b.exact, false);
  assert.equal(b.slicer, null, 'no slicer produced this');
  assert.ok(b.price > 0);
});

test('the route is off unless the shop switched it on — and refuses BEFORE reading the body', async () => {
  store.settings.lanApi.intakeQuote.enabled = false;
  try {
    const r = await estimate('part.3mf', slicedZip());
    assert.equal(r.status, 403, 'a closed door, not a 200 with a sad message');
    const b = await r.json();
    assert.equal(b.ok, false);
    assert.equal(b.reason, 'off');
    assert.equal(b.price, undefined, 'no number leaks from a refusal');
  } finally {
    store.settings.lanApi.intakeQuote.enabled = true;
  }
});

test('it needs an intake session or token, like the intake submit does', async () => {
  const r = await estimate('part.3mf', slicedZip(), { noAuth: true });
  assert.equal(r.status, 401);
});

