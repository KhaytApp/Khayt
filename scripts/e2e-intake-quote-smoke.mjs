#!/usr/bin/env node
/**
 * E2E: a customer prices their own model through the shop's intake form.
 *
 * test/lan-intake-estimate.test.js already drives the HTTP surface against a
 * real server. What only a running app can show is the rest of the loop: that
 * the SETTINGS PANEL writes a config the server actually honours, that the
 * config survives a store round-trip, and that a submitted request lands in the
 * shop's waiting list carrying the server's own figure.
 *
 * Requires display (use xvfb-run on Linux CI).
 */
import fs from 'fs';
import zipWrite from '../lib/zip-write.js';
import { E2E_LAN_PORT, dismissWizard, launchApp, makeUserDataDir, switchTab } from './e2e/helpers.mjs';

const userData = makeUserDataDir();
let electronApp;
const BASE = `http://127.0.0.1:${E2E_LAN_PORT}`;

const PRUSA_CFG = [
  '; generated by PrusaSlicer 2.8.0',
  '; estimated printing time (normal mode) = 3h 12m 40s',
  '; filament used [g] = 41.83',
].join('\n');

const TETRA = '<?xml version="1.0"?><model unit="millimeter"><resources>'
  + '<object id="1" type="model"><mesh><vertices>'
  + '<vertex x="0" y="0" z="0"/><vertex x="60" y="0" z="0"/>'
  + '<vertex x="0" y="60" z="0"/><vertex x="0" y="0" z="60"/>'
  + '</vertices><triangles>'
  + '<triangle v1="0" v2="2" v3="1"/><triangle v1="0" v2="1" v3="3"/>'
  + '<triangle v1="0" v2="3" v3="2"/><triangle v1="1" v2="2" v3="3"/>'
  + '</triangles></mesh></object></resources>'
  + '<build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 0 0 0"/></build></model>';

const sliced3mf = () => zipWrite.writeZip([
  { name: '3D/3dmodel.model', data: Buffer.from(TETRA, 'utf8') },
  { name: 'Metadata/Slic3r_PE.config', data: Buffer.from(PRUSA_CFG, 'utf8') },
]);

/** Configure the shop THROUGH the settings panel, not by writing the store. */
async function configureViaSettingsPanel(window) {
  await switchTab(window, 'settings-tab');
  // The LAN panel lives under Settings → Connections. Navigating there rather than
  // reaching past the sidebar also proves a shop can actually get to these
  // controls — a hidden checkbox is not a feature anyone can switch on.
  await window.click('.settings-nav-item[data-settings-section="connections"]');
  await window.waitForSelector('#settings-panel-connections.active');
  await window.evaluate(() => {
    // A preset to price against — the panel offers whatever the shop has.
    if (!Array.isArray(window.printers)) window.printers = [];
    if (!printers.some((p) => p.id === 'E2E-PRESET')) {
      printers.push({
        id: 'E2E-PRESET', name: 'E2E Printer', wearRate: 0.75, powerDraw: 150,
        elecRate: 0.18, laborRate: 90, failureRate: 10, prepTime: 0.25, postTime: 0.5,
      });
    }
    settings.lanApi = { ...(settings.lanApi || {}), enabled: true, port: 13219, bindLan: 'loopback' };
    renderLanApiSettings();
  });
  await window.waitForSelector('#lan_iq_enabled');

  // Tick the box and fill the panel exactly as a shop would.
  await window.evaluate(() => {
    const el = document.querySelector('#lanApiSection');
    const set = (sel, v) => { const f = el.querySelector(sel); if (f) f.value = String(v); };
    const box = el.querySelector('#lan_iq_enabled');
    box.checked = true;
    box.dispatchEvent(new Event('change', { bubbles: true }));
    set('#lan_iq_preset', 'E2E-PRESET');
    set('#lan_iq_spool_cost', 90);
    set('#lan_iq_spool_weight', 1000);
    set('#lan_iq_margin', 40);
    set('#lan_iq_waste', 3);
    saveLanApiSettingsFromForm({ restartServer: false });
    saveAll();
  });

  const stored = await window.evaluate(() => JSON.parse(JSON.stringify(settings.lanApi.intakeQuote || {})));
  if (!stored.enabled) throw new Error('the panel did not record "enabled"');
  if (stored.presetId !== 'E2E-PRESET') throw new Error(`presetId was ${stored.presetId}`);
  if (stored.marginPct !== 40) throw new Error(`marginPct was ${stored.marginPct}`);
  // Shown as a percentage, stored as a fraction — a 3 that persists as 3 would
  // add 300% waste to every customer's quote.
  if (Math.abs(stored.wastePct - 0.03) > 1e-9) throw new Error(`wastePct was ${stored.wastePct}, expected 0.03`);
  return stored;
}

async function startServer(window) {
  const r = await window.evaluate(() => window.hubAPI.startLanServer({
    port: 13219, pin: 'e2e-smoke-pin', bindLan: 'loopback',
  }));
  if (!r || !r.ok) throw new Error(`LAN server did not start: ${JSON.stringify(r)}`);
}

/**
 * Act like the customer's browser: visit the form, take the intake session
 * cookie, and send it back. Node's fetch keeps no cookie jar, so this is the
 * bit a real browser does for free — and skipping it is why an unauthenticated
 * estimate request is correctly refused.
 */
let intakeCookie = '';
async function openIntakeSession() {
  // Opening the form IS what grants the session — there is no separate sign-in
  // for a customer. Grabbing it once also matters because each fresh grant eats
  // into the per-visitor rate limit.
  const r = await fetch(`${BASE}/intake`);
  const raw = r.headers.getSetCookie?.() || [];
  intakeCookie = raw.map((c) => c.split(';')[0]).join('; ');
  if (!intakeCookie) throw new Error('opening /intake issued no session cookie');
  return r.text();
}
const withSession = (extra = {}) => ({ ...extra, ...(intakeCookie ? { cookie: intakeCookie } : {}) });

/** Poll a fetch until it satisfies `ok`, or give up. */
async function until(label, fn, ok, ms = 30_000) {
  const deadline = Date.now() + ms;
  let last;
  for (;;) {
    last = await fn();
    if (ok(last)) return last;
    if (Date.now() > deadline) throw new Error(`${label} — gave up after ${ms}ms`);
    await new Promise((r) => setTimeout(r, 250));
  }
}

/**
 * The intake page must offer the upload once the shop has switched it on.
 *
 * Polled, not asserted once: the renderer saves the store through the main
 * process, so the LAN server learns about the change a moment later.
 */
async function testFormOffersUpload() {
  const html = await until(
    'the intake form never grew an upload field',
    () => fetch(`${BASE}/intake`, { headers: withSession() }).then((r) => r.text()),
    (t) => /id="modelFile"/.test(t));
  if (!/not stored/.test(html)) throw new Error('the form does not tell the customer the file is not kept');
}

async function testCustomerGetsAPrice() {
  const r = await fetch(`${BASE}/api/intake/estimate?name=part.3mf`, {
    method: 'POST',
    headers: withSession({ 'content-type': 'application/octet-stream' }),
    body: sliced3mf(),
  });
  const b = await r.json();
  if (!b.ok) throw new Error(`no price came back: ${JSON.stringify(b)}`);
  if (!(b.price > 0)) throw new Error(`price was ${b.price}`);
  if (b.exact !== true) throw new Error('a sliced file should price as exact');
  if (b.binding !== false) throw new Error('a public estimate must never claim to be binding');
  if (!b.ref) throw new Error('no reference was issued');
  return b;
}

/** The submitted request must carry OUR figure, not one the browser made up. */
async function testSubmissionCarriesOurFigure(window, est) {
  const r = await fetch(`${BASE}/api/intake`, {
    method: 'POST',
    headers: withSession({ 'content-type': 'application/json' }),
    body: JSON.stringify({
      name: 'E2E Customer',
      description: 'Please print this bracket',
      consent: true,
      estimateRef: est.ref,
      estValue: 999999,                      // the lie a hostile browser tells
    }),
  });
  if (r.status !== 200) throw new Error(`intake submit returned ${r.status}: ${await r.text()}`);

  // …and it must reach the shop's own waiting list, through the real store.
  await window.waitForFunction(
    () => (typeof waitingList === 'undefined' ? [] : waitingList).some((w) => w.clientName === 'E2E Customer'),
    null, { timeout: 30_000 }).catch(async (e) => {
    const seen = await window.evaluate(() => ({
      len: (typeof waitingList === 'undefined' ? [] : waitingList).length,
      names: (typeof waitingList === 'undefined' ? [] : waitingList).slice(0, 5).map((w) => w.clientName),
    }));
    throw new Error(`${e.message} — waitingList had ${seen.len}: ${JSON.stringify(seen.names)}`);
  });
  const entry = await window.evaluate(() => JSON.parse(JSON.stringify(
    (typeof waitingList === 'undefined' ? [] : waitingList).find((w) => w.clientName === 'E2E Customer') || null)));
  if (!entry) throw new Error('the request never reached the waiting list');
  if (entry.estValue !== est.price) {
    throw new Error(`waiting list shows ${entry.estValue}, the server quoted ${est.price}`);
  }
  if (!entry.modelQuote || entry.modelQuote.exact !== true) {
    throw new Error(`the quote's provenance was lost: ${JSON.stringify(entry.modelQuote)}`);
  }
  if (entry.modelQuote.binding !== false) throw new Error('stored as binding');
}

/** Switching it back off must close the door again. */
async function testTurningItOffClosesTheDoor(window) {
  await window.evaluate(() => {
    const el = document.querySelector('#lanApiSection');
    const box = el.querySelector('#lan_iq_enabled');
    box.checked = false;
    box.dispatchEvent(new Event('change', { bubbles: true }));
    saveLanApiSettingsFromForm({ restartServer: false });
    saveAll();
  });
  await until(
    'the estimate route stayed open after being switched off',
    () => fetch(`${BASE}/api/intake/estimate?name=part.3mf`, {
      method: 'POST',
      headers: withSession({ 'content-type': 'application/octet-stream' }),
      body: sliced3mf(),
    }).then((r) => r.status),
    (status) => status === 403);
  const html = await (await fetch(`${BASE}/intake`, { headers: withSession() })).text();
  if (/id="modelFile"/.test(html)) throw new Error('the upload field is still on the form');
}

try {
  ({ electronApp } = await launchApp(userData));
  const window = await electronApp.firstWindow();
  window.setDefaultTimeout(120_000);
  await dismissWizard(window);

  await configureViaSettingsPanel(window);
  await startServer(window);
  await openIntakeSession();
  await testFormOffersUpload();
  const est = await testCustomerGetsAPrice();
  await testSubmissionCarriesOurFigure(window, est);
  await testTurningItOffClosesTheDoor(window);

  console.log('e2e-intake-quote: ok (panel → server → price %s → waiting list → off)', est.price);
} finally {
  if (electronApp) await electronApp.close().catch(() => {});
  fs.rmSync(userData, { recursive: true, force: true });
}
