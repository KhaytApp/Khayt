#!/usr/bin/env node
'use strict';
/**
 * Write lib/release-gates.json: each released version's "Before you update"
 * items, read out of CHANGELOG.md the way the updater reads a release body.
 *
 * WHY A FILE IN THE APP. The gate lives in the update dialog (lib/updater.js
 * notesSince), so only electron-updater installs ever saw it. A Microsoft
 * Store install is updated by the Store, and a manual install by its
 * installer: both arrive at a major change without a word (4.11.0 release,
 * Nov 20). CHANGELOG.md does not ship inside the app, so the first launch
 * after a version change reads its gates from this file instead
 * (lib/main/launch-gate.js).
 *
 *   node scripts/write-release-gates.js          write it
 *   node scripts/write-release-gates.js --check  exit 1 when it is stale
 *
 * The cut runs it (docs/BETA-RELEASE.md); test/release-gates.test.js fails a
 * PR whose CHANGELOG and this file disagree, so a cut cannot ship without it.
 */
const fs = require('fs');
const path = require('path');
const { parseMajorChanges } = require('../lib/major-changes.js');
const { sectionFor } = require('./changelog-section.js');
const { compareVersions } = require('../lib/launch-gate.js');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'lib', 'release-gates.json');
/** Enough releases back to cover a shop that skipped a month of weekly cuts (per app). */
const KEEP = 24;

/**
 * The Mac's sections share this CHANGELOG (VERSIONING.md): `4.0.0-alpha.N` /
 * `4.0.0-beta.N`, each opening with "*Khayt for macOS only.". Both must agree,
 * or the write fails: either alone can drift, and a Mac section in `gates`
 * would hold Windows shops on a Mac change (agreed with the Mac, Nov 23).
 */
const MAC_VERSION = /^4\.0\.0-(?:alpha|beta)\.\d+$/;
const MAC_MARKER = /^\*Khayt for macOS only\./m;

function itemsOf(section) {
  const r = parseMajorChanges(section);
  return r && r.needsConsent && Array.isArray(r.items) && r.items.length ? r.items : null;
}

function build(changelog) {
  const desktop = [];
  const mac = [];
  const disagree = [];
  for (const m of changelog.matchAll(/^## \[(\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?)\] - \d{4}-\d{2}-\d{2}/gm)) {
    const v = m[1];
    const section = sectionFor(changelog, v);
    if (!section) continue;
    const shaped = MAC_VERSION.test(v);
    const marked = MAC_MARKER.test(section);
    if (shaped !== marked) { disagree.push(v); continue; }
    const list = shaped ? mac : desktop;
    if (!list.some((x) => x.v === v)) list.push({ v, section });
  }
  if (disagree.length) {
    throw new Error('CHANGELOG: a section\'s version and its "*Khayt for macOS only." line disagree: ' + disagree.join(', ')
      + '. A Mac section is 4.0.0-alpha.N or 4.0.0-beta.N AND opens with that line; a desktop section has neither.');
  }
  const gates = {};
  for (const { v, section } of desktop.slice(0, KEEP)) { const it = itemsOf(section); if (it) gates[v] = it; }
  // The Mac's sections are not in date order in the file: newest by version.
  mac.sort((a, b) => compareVersions(b.v, a.v));
  const macGates = {};
  for (const { v, section } of mac.slice(0, KEEP)) { const it = itemsOf(section); if (it) macGates[v] = it; }
  return { about: 'Generated by scripts/write-release-gates.js from CHANGELOG.md. Do not edit by hand. `gates` are Windows/Linux versions; `mac` are the Mac app\'s (mac/version.json).', gates, mac: macGates };
}

function render(obj) { return JSON.stringify(obj, null, 1) + '\n'; }

if (require.main === module) {
  const want = render(build(fs.readFileSync(path.join(ROOT, 'CHANGELOG.md'), 'utf8')));
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (have !== want) {
      console.error('lib/release-gates.json is stale: run `node scripts/write-release-gates.js` and commit it.');
      process.exit(1);
    }
    console.log('release-gates ok');
  } else {
    fs.writeFileSync(OUT, want);
    console.log('wrote ' + path.relative(ROOT, OUT));
  }
}

module.exports = { build, render, OUT, MAC_VERSION, MAC_MARKER };
