/**
 * E2E smoke — Send to printer, checked against the printer before it goes,
 * and the printer card's seven states (Figma desktop page 129: S1, S1b, S1c,
 * S2; AR the same).
 *
 * The real path end to end: the machine card's send (sliceAndPrintForMachine)
 * asks main's REAL open dialog (stubbed in main to answer with a fixture
 * file, since nobody is there to click), main reads the file
 * (hub:printer-send-facts), and the window runs lib/send-checks.js over it,
 * the machine and the printer's poll entry. Nothing is sent: every dialog is
 * cancelled, and a stop's Send cannot be pressed. The printers are
 * documentation addresses (192.0.2.x), so main's polls never reach a device.
 *
 * Run: npm run test:e2e:sendchecks   (CI wraps it in xvfb-run)
 */
import fs from 'node:fs'; import os from 'node:os'; import path from 'node:path';
import { launchApp, makeUserDataDir, dismissWizard } from './e2e/helpers.mjs';

const ok = (c, m) => { if (!c) throw new Error('ASSERT FAILED: ' + m); console.log('  ✓ ' + m); };
const shot = process.env.KHAYT_SHOT_DIR || '';

// ── The files (the frames' sample data) ──────────────────────────────────
const poly = (x0, y0, w, h) => `[[${x0},${y0}],[${x0 + w},${y0}],[${x0 + w},${y0 + h}],[${x0},${y0 + h}]]`;
const placed = (w, h, filaments) => [
  '; generated by OrcaSlicer 2.2.0',
  `EXCLUDE_OBJECT_DEFINE NAME=bracket CENTER=${40 + w / 2},${40 + h / 2} POLYGON=${poly(40, 40, w, h)}`,
  'G90', 'M83', 'G1 Z0.2', 'G1 X50 Y50 E1', 'G1 X60 Y60 E1',
  '; max_z_height: 30.00',
  ...(filaments ? [
    '; filament used [g] = 0.00, 30.00, 0.00, 8.00',
    '; filament used [mm] = 0.00, 10000.00, 0.00, 2600.00',
    '; filament_type = PLA;PLA;PLA;PLA',
    '; filament_colour = #FFFFFF;#000000;#FFFFFF;#FFFFFF',
  ] : ['; filament used [g] = 38.00']),
  '; estimated printing time (normal mode) = 1h 12m 0s',
  '; printer_model = Snapmaker U1',
  '; printable_area = 0x0,270x0,270x270,0x270',
  '; printable_height = 270', ''].join('\n');
// No object list: only the moves say where it prints (S1c).
const moves = ['; generated by PrusaSlicer 2.8.1', 'G90', 'M83', 'G1 Z0.2', 'G1 X10 Y20',
  'G1 X295 Y20 E5', 'G1 X295 Y160 E5', 'G1 X10 Y160 E5', 'G1 X10 Y20 E5',
  '; filament used [g] = 38.00', '; estimated printing time (normal mode) = 1h 12m 0s', ''].join('\n');

const fileDir = fs.mkdtempSync(path.join(os.tmpdir(), 'khayt-sendchecks-'));
const files = {
  S1: path.join(fileDir, 's1', 'bracket-kit-plate-2.gcode'),
  S1b: path.join(fileDir, 's1b', 'bracket-kit-plate-2.gcode'),
  S1c: path.join(fileDir, 's1c', 'bracket-kit-plate-2.gcode'),
};
for (const [k, body] of [['S1', placed(182, 140, true)], ['S1b', placed(300, 210, false)], ['S1c', moves]]) {
  fs.mkdirSync(path.dirname(files[k]), { recursive: true });
  fs.writeFileSync(files[k], body);
}

// ── The book ────────────────────────────────────────────────────────────
const api = (type, n) => ({ type, host: `192.0.2.${n}` });
const machines = [
  { id: 'U1', name: 'Workshop U1', color: '#3b82f6', printerModel: 'Snapmaker U1', toolheads: 4, bed: { x: 270, y: 270, z: 270 }, printerApi: api('moonraker', 40) },
  { id: 'CO', name: 'Prusa CORE One', color: '#f97316', printerModel: 'Prusa CORE One', bed: { x: 250, y: 220, z: 270 }, printerApi: api('prusalink', 41) },
  { id: 'P1', name: 'Bambu P1S', color: '#22c55e', printerApi: { ...api('bambu', 42), serial: '01P00A000000000', accessCode: '00000000' } },
  { id: 'EN', name: 'Ender 3', color: '#eab308', printerApi: api('octoprint', 43) },
  { id: 'RB', name: 'Resin bay', color: '#a855f7', printerApi: api('sdcp', 44) },
  { id: 'VO', name: 'Voron 2.4', color: '#ef4444', printerApi: api('moonraker', 45) },
  { id: 'OP', name: 'Old Prusa', color: '#64748b', printerApi: api('octoprint', 46) },
];

async function stubPick(electronApp, file) {
  await electronApp.evaluate(({ dialog }, p) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [p] });
  }, file);
}

/** Open the real send for `machineId` on `file`; wait for the dialog. */
async function openSend(window, electronApp, machineId, file, cache) {
  await stubPick(electronApp, file);
  await window.evaluate(({ id, cache }) => {
    Object.assign(machineStatusCache, cache);
    sliceAndPrintForMachine(id);   // not awaited: it waits for the person
  }, { id: machineId, cache });
  await window.waitForSelector('.sc-dialog', { timeout: 10_000 });
  return window.evaluate(() => {
    const d = document.querySelector('.sc-dialog');
    return {
      head: d.querySelector('.sc-head').innerText,
      file: d.querySelector('.sc-file').innerText,
      meta: d.querySelector('.sc-meta')?.innerText || '',
      rows: [...d.querySelectorAll('.sc-row')].map((r) => ({ code: r.dataset.scCode, kind: r.className.replace(/.*is-/, ''), text: r.innerText })),
      send: { label: d.querySelector('[data-act="send"]').innerText, disabled: d.querySelector('[data-act="send"]').disabled },
      dir: getComputedStyle(d).direction,
    };
  });
}

async function cancel(window, how) {
  if (how === 'escape') await window.keyboard.press('Escape');
  else await window.click('.sc-dialog [data-act="cancel"]');
  await window.waitForFunction(() => !document.querySelector('.sc-dialog'), null, { timeout: 5000 });
}

async function run(lang) {
  const dir = makeUserDataDir();
  fs.writeFileSync(path.join(dir, 'khayt-store.json'), JSON.stringify({
    settings: { firstRun: false, firstRunDone: true, bizName: 'Sample Shop', lang, mode: 'professional' },
    machines, printLog: [], clients: [], inventory: [],
  }));
  const { electronApp, window } = await launchApp(dir);
  try {
    await dismissWizard(window);
    await window.setViewportSize({ width: 1400, height: 900 });
    await window.evaluate((l) => { if (typeof i18n !== 'undefined') i18n.set(l); openSettingsSection('printers'); renderMachines(); }, lang);
    await window.waitForTimeout(600);
    const now = Date.now();
    const ended = now - 40 * 60000;

    // S1: fits, tool 2 has the wrong material, the bed nobody cleared, tool 4 not reported.
    const s1 = await openSend(window, electronApp, 'U1', files.S1, {
      U1: { state: 'complete', progress: 100, lastActivityAt: ended, lastUpdated: now,
        loaded: [{ slot: 1, hex: '#FFFFFF', material: 'PETG' }, { slot: 3, hex: null, material: 'NONE' }] },
    });
    ok(s1.rows.map((r) => r.code).join() === 'fits,bed-not-cleared,material-mismatch,head-not-reported',
      `${lang} S1: main read the file and the four checks are drawn (${s1.rows.map((r) => r.code)})`);
    ok(s1.rows.map((r) => r.kind).join() === 'ok,warn,warn,info', `${lang} S1: tick, two warnings, one not checked`);
    ok(!s1.send.disabled, `${lang} S1: a warning never stops the send`);
    ok(s1.file === 'bracket-kit-plate-2.gcode', `${lang} S1: the file's own name`);
    if (lang === 'en') {
      ok(s1.head === 'Send to Workshop U1' && s1.send.label === 'Send anyway', 'S1: "Send to Workshop U1", and Send anyway');
      ok(s1.meta === '1 h 12 min · 38 g', 'S1: the slicer\'s time and weight');
      ok(s1.rows[0].text.includes('Fits the bed: 182 × 140 mm on 270 × 270 mm'), 'S1: Fits the bed, from the placed extents');
      ok(/Tool 2 has PETG\s+loaded; the file asks for PLA/.test(s1.rows[2].text), 'S1: tool 2 is PETG, the file asks for PLA');
      ok(/Tool 4: the printer didn’t say what is loaded/.test(s1.rows[3].text), 'S1: tool 4 not reported, nothing assumed');
      ok(/Bed is clear/.test(s1.rows[1].text), 'S1: the bed line names the Bed is clear button');
    } else {
      ok(s1.dir === 'rtl', 'ar S1: the dialog runs right to left');
      ok(s1.head.startsWith('إرسال إلى') && s1.send.label === 'أرسل على أي حال', 'ar S1: Arabic title and Send anyway');
      const bdi = await window.evaluate(() => document.querySelectorAll('.sc-dialog bdi').length);
      ok(bdi >= 8, `ar S1: names, sizes and materials are isolated in <bdi> (${bdi})`);
    }
    if (shot) await (await window.$('.sc-dialog')).screenshot({ path: path.join(shot, `p129-S1-${lang}.png`) });
    await cancel(window, 'button');
    ok(true, `${lang} S1: Cancel closes it and nothing is sent`);

    // S1b: too big on the placed extents. Send stays off.
    await window.evaluate(() => { machines.find((m) => m.id === 'U1').bedClearedAt = new Date().toISOString(); });
    const s1b = await openSend(window, electronApp, 'U1', files.S1b, { U1: { state: 'standby', lastActivityAt: ended, lastUpdated: now } });
    ok(s1b.rows.length === 1 && s1b.rows[0].code === 'bed-footprint' && s1b.rows[0].kind === 'block', `${lang} S1b: one stop, too big for the bed`);
    ok(s1b.send.disabled, `${lang} S1b: Send is off`);
    if (lang === 'en') {
      ok(/Too big for this bed: 300 × 210 mm on 270 × 270 mm/.test(s1b.rows[0].text) && s1b.send.label === 'Send', 'S1b: the sizes, and plain Send (off)');
      await window.click('.sc-dialog [data-act="send"]', { force: true });
      ok(await window.evaluate(() => !!document.querySelector('.sc-dialog')), 'S1b: pressing the off Send does nothing');
    }
    if (shot) await (await window.$('.sc-dialog')).screenshot({ path: path.join(shot, `p129-S1b-${lang}.png`) });
    await cancel(window, 'escape');
    ok(true, `${lang} S1b: Escape closes it`);

    // S1c: only the moves were measured. A warning, never a stop.
    await window.evaluate(() => { machines.find((m) => m.id === 'CO').bedClearedAt = new Date().toISOString(); });
    const s1c = await openSend(window, electronApp, 'CO', files.S1c, { CO: { state: 'IDLE', lastActivityAt: ended, lastUpdated: now } });
    ok(s1c.rows.length === 1 && s1c.rows[0].code === 'bed-footprint' && s1c.rows[0].kind === 'warn', `${lang} S1c: moves only, so a warning`);
    ok(!s1c.send.disabled, `${lang} S1c: Send anyway stays on`);
    if (lang === 'en') {
      ok(/The printed area may not fit: 285 × 140 mm on 250 × 220 mm/.test(s1c.rows[0].text) && /Measured from the file’s moves/.test(s1c.rows[0].text), 'S1c: the sizes, and why it is only a warning');
    }
    if (shot) await (await window.$('.sc-dialog')).screenshot({ path: path.join(shot, `p129-S1c-${lang}.png`) });
    await cancel(window, 'button');

    // A path the person did not pick is not read.
    const refused = await window.evaluate((p) => window.hubAPI.printerSendFacts({ gcodePath: p }), path.join(dir, 'khayt-store.json'));
    ok(refused && refused.ok === false && refused.error === 'not_picked', `${lang}: main reads only a file the person picked`);

    // S2: the seven states on the cards, Paused its own.
    await window.evaluate((now) => {
      Object.assign(machineStatusCache, {
        U1: { state: 'printing', progress: 62, lastUpdated: now },
        CO: { state: 'PAUSED', progress: 40, lastUpdated: now },
        P1: { state: 'Idle', lastUpdated: now },
        EN: { state: '', error: 'ETIMEDOUT', consecutiveFailures: 1, lastUpdated: now },
        VO: { state: 'error', lastUpdated: now },
        OP: { state: '', error: 'ECONNREFUSED', consecutiveFailures: 9, lastUpdated: now },
      });
      delete machineStatusCache.RB;
      renderMachines();
    }, now);
    await window.waitForTimeout(200);
    const states = await window.evaluate(() => Object.fromEntries([...document.querySelectorAll('#machinesList [data-machine-live]')]
      .map((e) => { const s = e.querySelector('.machine-live-state'); return [e.dataset.machineLive, s ? [s.className.replace('machine-live-state is-', ''), s.innerText] : null]; })));
    const cls = Object.fromEntries(Object.entries(states).map(([k, v]) => [k, v && v[0]]));
    ok(JSON.stringify(cls) === JSON.stringify({ U1: 'printing', CO: 'paused', P1: 'idle', EN: 'reconnecting', RB: 'unknown', VO: 'error', OP: 'offline' }),
      `${lang} S2: seven states, Paused its own (${JSON.stringify(cls)})`);
    if (lang === 'en') {
      ok(states.U1[1] === 'Printing · 62%' && states.CO[1] === 'Paused · 40%' && states.RB[1] === 'Not known yet' && states.VO[1] === 'Error',
        `S2: the words (${JSON.stringify(states)})`);
      const colours = await window.evaluate(() => {
        const c = (id) => getComputedStyle(document.querySelector(`[data-machine-live="${id}"] .machine-live-state`)).color;
        return { paused: c('CO'), printing: c('U1'), idle: c('P1') };
      });
      ok(colours.paused !== colours.printing && colours.paused !== colours.idle, 'S2: Paused has its own colour');
    } else {
      ok(states.CO[1].startsWith('متوقفة مؤقتاً'), 'ar S2: متوقفة مؤقتاً');
    }
    if (shot) await (await window.$('#machinesList')).screenshot({ path: path.join(shot, `p129-S2-${lang}.png`) });
  } finally { await electronApp.close(); }
}

let failed = false;
try { await run('en'); await run('ar'); console.log('\ne2e-send-checks: ok'); }
catch (e) { failed = true; console.error('\ne2e-send-checks FAILED: ' + (e && e.message || e)); }
finally { try { fs.rmSync(fileDir, { recursive: true, force: true }); } catch (_) { /* tmp */ } }
process.exit(failed ? 1 : 0);
