const rawPub = (k) => crypto.createPublicKey(k).export({ type: 'spki', format: 'der' }).subarray(12).toString('base64');
async function post(p, body, headers = {}) {
  const res = await fetch(BASE + p, { method: 'POST', headers: { 'content-type': 'application/json', ...headers }, body: JSON.stringify(body) });
  return { status: res.status, json: await res.json().catch(() => null) };
}
/** The plugin: commit, offer, reveal. Returns the number it shows and its device id. */
async function pluginAsks(name) {
  const pair = crypto.generateKeyPairSync('x25519');
  const publicKey = rawPub(pair.privateKey);
  const nonce = crypto.randomBytes(16).toString('base64');
  const o = await post('/api/connectors/pair', { v: 2, commit: CP.commitment(publicKey, nonce).toString('base64'), name, app: 'OrcaSlicer', version: '2.3.1' });
  if (o.status !== 200) throw new Error('offer: ' + o.status + ' ' + JSON.stringify(o.json));
  const r = await post(`/api/connectors/pair/${o.json.pairId}/reveal`, { publicKey, nonce }, { 'x-khayt-poll': o.json.pollSecret });
  if (r.status !== 200) throw new Error('reveal: ' + r.status);
  return { check: CP.checkNumber(o.json.deviceId, o.json.identity, o.json.publicKey, publicKey, nonce), id: o.json.deviceId };
}

/** One file in the inbox, as lib/main/slicer-inbox.js file() leaves it. */
function fileIntoInbox(userData, n, name, info) {
  const id = `SU-${Date.now() - n * 60000}-${crypto.randomBytes(2).toString('hex')}`;
  const dir = path.join(userData, 'From slicer', id);
  fs.mkdirSync(dir, { recursive: true });
  const body = Buffer.from(`; generated by ${info.slicer || 'OrcaSlicer'}\nG28\nG1 X10 Y10 E1\n; ${name} ${n}\n`);
  fs.writeFileSync(path.join(dir, name), body);
  const item = { id, name, arrived: new Date(Date.now() - n * 60000).toISOString().replace(/\.\d+Z$/, 'Z'), bytes: body.length,
    sha256: crypto.createHash('sha256').update(body).digest('hex'), ...info };
  fs.writeFileSync(path.join(dir, 'info.json'), JSON.stringify(item));
  return item;
}

