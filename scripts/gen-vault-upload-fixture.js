#!/usr/bin/env node
'use strict';
/**
 * Writes test/fixtures/vault-upload-fixture/expected.json from inputs.json.
 *
 * Built from node:crypto primitives ONLY (hkdfSync, aes-256-gcm, createHmac),
 * NOT from lib/vault-crypto.js or lib/vault-upload.js — a second, independent
 * reading of docs/vault-format.md and VaultUpload.swift, so the JS upload
 * (test/vault-upload.test.js) and the Mac's VaultUpload are both checked
 * against it rather than against themselves.
 *
 *   node scripts/gen-vault-upload-fixture.js            # rewrite expected.json
 *   node scripts/gen-vault-upload-fixture.js --check    # exit 1 if it would change
 */
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const DIR = path.join(__dirname, '..', 'test', 'fixtures', 'vault-upload-fixture');
const CHUNK_BYTES = 4194304;
const TAG = 16;

const H = (s) => Buffer.from(s, 'hex');
const sha = (b) => crypto.createHash('sha256').update(b).digest();
const hkdf = (ikm, salt, info) => Buffer.from(crypto.hkdfSync('sha256', ikm, Buffer.from(salt, 'utf8'), Buffer.from(info, 'utf8'), 32));
function gcm(key, nonce, pt, aad) {
  const c = crypto.createCipheriv('aes-256-gcm', key, nonce);
  c.setAAD(Buffer.from(aad, 'utf8'));
  return Buffer.concat([c.update(pt), c.final(), c.getAuthTag()]);
}
const sealWithNonce = (key, nonce, pt, aad) => Buffer.concat([nonce, gcm(key, nonce, pt, aad)]);

/** The plaintext recipe in inputs.json: byte k = (k * mul + add) mod 256. */
function plaintext(r) {
  const b = Buffer.alloc(r.size);
  for (let k = 0; k < r.size; k++) b[k] = (k * r.mul + r.add) & 0xff;
  return b;
}

function build(inp) {
  const dek = H(inp.shopDek), dk = H(inp.dataKey);
  const { fileId, uploadId } = inp;
  const pt = plaintext(inp.plaintext);
  const size = pt.length;
  const n = size === 0 ? 1 : Math.ceil(size / CHUNK_BYTES);
  const vaultKey = hkdf(dek, 'khayt-vault-v1', 'vault');
  const dedupeKey = hkdf(dek, 'khayt-vault-v1', 'dedupe');
  const chunkKey = hkdf(dk, uploadId, 'khayt-vault-chunk-v1');
  const chunks = [];
  for (let i = 0; i < n; i++) {
    const p = pt.subarray(i * CHUNK_BYTES, Math.min(size, (i + 1) * CHUNK_BYTES));
    const nonce = Buffer.alloc(12);
    nonce.writeBigUInt64BE(BigInt(i), 4);
    const last = i === n - 1;
    const sealed = gcm(chunkKey, nonce, p, `khayt-vault-v1|${fileId}|${uploadId}|${i}|${last ? 1 : 0}`);
    chunks.push({ index: i, plaintextBytes: p.length, size: sealed.length, nonce: nonce.toString('hex'),
      plaintextSha256: sha(p).toString('hex'), sha256: sha(sealed).toString('hex'),
      first16: sealed.subarray(0, 16).toString('hex'), last16: sealed.subarray(sealed.length - 16).toString('hex') });
  }
  const chunkHashes = chunks.map((c) => c.sha256);
  const manifestJson = `{"v":1,"chunkBytes":${CHUNK_BYTES},"size":${size},"chunks":[${chunkHashes.map((h) => `"${h}"`).join(',')}]}`;
  const manifestHash = sha(Buffer.from(manifestJson, 'utf8')).toString('hex');
  const plainSha = sha(pt);
  const dedupeTag = crypto.createHmac('sha256', dedupeKey).update(plainSha).digest('hex');
  const seq = (inp.lastSeq == null ? 0 : inp.lastSeq) + 1;
  const wrappedKey = sealWithNonce(vaultKey, H(inp.nonces.wrap), dk, `khayt-vault-dk|${fileId}|${uploadId}`);
  const versionMetaJson = `{"manifest":${manifestJson},"size":${size},"seq":${seq}}`;
  const versionMeta = sealWithNonce(vaultKey, H(inp.nonces.versionMeta), Buffer.from(versionMetaJson, 'utf8'),
    `khayt-vault-vmeta|${fileId}|${uploadId}`);
  // VaultMeta through JSONEncoder(.sortedKeys, .withoutEscapingSlashes): keys
  // sorted, nil optionals left out, "/" not escaped, non-ASCII as raw UTF-8.
  const m = { seq, uploadId, manifestHash, size, sha256: plainSha.toString('hex'), name: inp.name,
    path: inp.path, kind: inp.kind };
  if (inp.key != null) m.key = inp.key;
  if (inp.recordId != null) m.recordId = inp.recordId;
  const metaJson = '{' + Object.keys(m).sort().map((k) => JSON.stringify(k) + ':' + JSON.stringify(m[k])).join(',') + '}';
  const meta = sealWithNonce(vaultKey, H(inp.nonces.meta), Buffer.from(metaJson, 'utf8'), `khayt-vault-meta|${fileId}|${uploadId}`);
  const sizes = chunks.map((c) => c.size);
  const startBody = { chunkBytes: CHUNK_BYTES, sizes, tag: dedupeTag };
  if (inp.existingFileId != null) startBody.fileId = inp.existingFileId;
  if (inp.baseVersion != null) startBody.baseVersion = inp.baseVersion;
  if (inp.deviceId != null) startBody.deviceId = inp.deviceId;
  return {
    _comment: 'Generated by scripts/gen-vault-upload-fixture.js from node:crypto only. Do not hand-edit.',
    plaintextSha256: plainSha.toString('hex'),
    size,
    dedupeTag,
    sizes,
    chunks,
    chunkHashes,
    manifestJson,
    manifestHash,
    seq,
    wrappedKey: wrappedKey.toString('base64'),
    versionMetaJson,
    versionMeta: versionMeta.toString('base64'),
    metaJson,
    meta: meta.toString('base64'),
    startBody,
    completeBody: { manifestHash, wrappedKey: wrappedKey.toString('base64'),
      versionMeta: versionMeta.toString('base64'), meta: meta.toString('base64') },
  };
}

const inputs = JSON.parse(fs.readFileSync(path.join(DIR, 'inputs.json'), 'utf8'));
const out = JSON.stringify(build(inputs), null, 2) + '\n';
const file = path.join(DIR, 'expected.json');
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (cur !== out) { console.error('expected.json is stale: run node scripts/gen-vault-upload-fixture.js'); process.exit(1); }
  console.log('expected.json is current');
} else {
  fs.writeFileSync(file, out);
  console.log('wrote', path.relative(process.cwd(), file));
}
